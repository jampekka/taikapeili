import assert from 'node:assert/strict';
import {MirrorCycle} from '../dist/cycle.js';
const face={center:{x:.5,y:.4},width:.3,height:.4,eyes:[{x:.4,y:.4},{x:.6,y:.4}]};
const c=new MirrorCycle();
for(let t=0;t<2000;t+=200)assert.equal(c.observe(null,t).capture,false,'Empty scenes must never trigger');
assert.equal(c.observe(face,2000).capture,false);
assert.equal(c.observe(face,2800).capture,false);
const first=c.observe(face,3000);assert.equal(first.capture,true,'A steady detected face triggers without input');
assert.equal(c.observe(face,3200).capture,false,'Only one in-flight transformation');
assert.equal(c.complete(first.ticket,3400),true);
assert.equal(c.observe(face,4000).hide,false);
assert.equal(c.observe(face,5200).hide,true,'Timed reveal returns to live');
assert.equal(c.observe(face,11000).capture,false);
const second=c.observe(face,11800);assert.equal(second.capture,true,'A remaining visitor triggers another reveal');
c.observe(null,12600);assert.equal(c.complete(second.ticket,12700),false,'A departed visitor must invalidate a pending result');
const reappear=c.observe(face,14000);assert.equal(reappear.capture,false);
const third=c.observe(face,15100);assert.equal(third.capture,true);
const moved={...face,center:{x:.8,y:.4}};c.observe(moved,15200);assert.equal(c.complete(third.ticket,15300),false,'A large position change invalidates the old face');
c.reset();assert.equal(c.complete(third.ticket,15400),false,'Reset cancels pending work');
console.log('PASS: empty scene, steady face, single in-flight capture, timed return, repeat, departure, movement, reset');
